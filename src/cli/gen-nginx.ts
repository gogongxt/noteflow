// Regenerates the nginx security-header snippet from a build manifest (the CSP
// hashes change per build). Write with --out: shell redirection truncates the
// target before this script can refuse.
import fs from 'node:fs';
import path from 'node:path';
import { basePathOf, loadConfig } from '../core/config.ts';
import { fatal, parseArgs } from '../core/util.ts';
import { buildCsp, hashesOf, type CspHashes } from '../core/csp.ts';

const args = parseArgs(process.argv.slice(2));
const cfg = await loadConfig(typeof args.config === 'string' ? path.resolve(process.cwd(), String(args.config)) : undefined).catch(fatal);
const manifestArg = args._[0];
const manifestFile = typeof manifestArg === 'string' ? manifestArg : cfg.manifestFile;
const outFile = typeof args.out === 'string' ? path.resolve(args.out) : null;

const refuse = (why: string): never => {
  console.error(`refusing to emit a CSP from ${manifestFile}: ${why}`);
  process.exit(1);
};

// The generated snippet serves the site at /; a base-path build (GitHub Pages
// style) is not what this template deploys.
if (basePathOf(cfg.url)) refuse(`cfg.url carries a base path (${basePathOf(cfg.url)}); this nginx template serves the site at /`);

const manifest = (() => {
  try {
    return JSON.parse(fs.readFileSync(manifestFile, 'utf8')) as { buildId?: string; audited?: boolean };
  } catch (err) {
    return refuse(`cannot read manifest: ${(err as Error).message}`);
  }
})();
// A --skip-audit CSP would silently strip every inline style in note bodies.
if (manifest.audited === false) refuse('manifest was built with --skip-audit; its style hashes are incomplete');
const hashes: CspHashes = (() => {
  try {
    return hashesOf(manifest);
  } catch (e) {
    return refuse(e instanceof Error ? e.message : String(e));
  }
})();
if (!hashes.script.length) refuse("no inline script hashes; the CSP would block the site's inline scripts");

const out = `# Generated by src/cli/gen-nginx.ts from ${manifestFile} (buildId ${manifest.buildId})
# ⚠️ Regenerate on every release: CSP hashes are over the final output bytes.
# ⚠️ nginx add_header directives are not inherited into locations that define
#    their own add_header; every such location must include this file.
add_header Content-Security-Policy "${buildCsp(hashes, cfg, true)}" always;
add_header X-Content-Type-Options "nosniff" always;
add_header Referrer-Policy "strict-origin-when-cross-origin" always;
add_header Permissions-Policy "camera=(), microphone=(), geolocation=()" always;
# One-year HSTS: once browsers accept it, HTTP fallback is refused outright —
# confirm the whole site is stable over HTTPS before extending this further.
add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;
`;

if (outFile) {
  const tmp = outFile + '.tmp';
  fs.writeFileSync(tmp, out);
  fs.renameSync(tmp, outFile);
  console.log(`wrote ${outFile} (buildId ${manifest.buildId})`);
} else {
  process.stdout.write(out);
}